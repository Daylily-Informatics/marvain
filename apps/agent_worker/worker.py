    async def _process_visual_observation_message(
        *,
        sender: str,
        message_session_id: str,
        artifact_uri: str,
        captured_at: str,
        visual_request_id: str,
    ) -> dict[str, Any]:
        visual_request_id = _require_runtime_text(visual_request_id, "visual_request_id")
        try:
            validate_livekit_sender_session(
                sender_identity=sender,
                expected_sender_identity=expected_participant_identity,
                message_session_id=message_session_id,
                expected_session_id=session_id,
            )
            captured_at_timestamp = validate_livekit_message_freshness(
                captured_at,
                field_name="captured_at",
                max_age_seconds=VISUAL_OBSERVATION_MAX_AGE_SECONDS,
            )
        except LiveKitMessageValidationError as exc:
            if exc.code in {"stale_session", "stale_message"}:
                await _invalidate_camera_observations(sender=sender, reason=f"rejected_{exc.code}")
            rejection_payload = {
                "contract_version": EVENT_CONTRACT_VERSION,
                "session_id": session_id,
                "message_session_id": message_session_id,
                "participant_identity": sender,
                "visual_request_id": visual_request_id,
                "captured_at": captured_at,
                "error": exc.code,
                "rejected_at": _isoformat_utc(),
            }
            hub_ingest_event(
                space_id=space_id,
                event_type="visual.observation_rejected",
                payload=rejection_payload,
                session_id=session_id,
            )
            await _publish_visual_observation_ack(
                {
                    "ok": False,
                    "error": exc.code,
                    "visual_request_id": visual_request_id,
                    "request_sender_identity": sender,
                }
            )
            return {"ok": False, "error": exc.code}

        observation = ""
        if not observation and artifact_uri:
            described = await asyncio.to_thread(_describe_visual_artifact, artifact_uri, agent_id=agent_id)
            observation = str(described or "").strip()

        if not observation:
            logger.info("Ignoring visual_observation from %s without analyzed observation text", sender)
            hub_ingest_event(
                space_id=space_id,
                event_type="visual.artifact_reference",
                payload={
                    "source": "livekit_browser_camera",
                    "artifact_uri": artifact_uri,
                    "captured_at": captured_at,
                    "visual_request_id": visual_request_id,
                    "participant_identity": sender,
                    "session_id": session_id,
                    "truthfulness_note": "artifact reference only; no visual observation text",
                },
                session_id=session_id,
            )
            await _publish_visual_observation_ack(
                {
                    "ok": False,
                    "error": "camera_enabled_but_visual_analysis_unavailable",
                    "visual_request_id": visual_request_id,
                    "request_sender_identity": sender,
                    "artifact_uri": artifact_uri,
                    "captured_at": captured_at,
                }
            )
            return {"ok": False, "error": "camera_enabled_but_visual_analysis_unavailable"}

        observation = observation[:800]
        source_event_id = hub_ingest_event(
            space_id=space_id,
            event_type="visual.observation",
            payload={
                "source": "livekit_browser_camera",
                "description": observation,
                "artifact_uri": artifact_uri,
                "captured_at": captured_at,
                "visual_request_id": visual_request_id,
                "participant_identity": sender,
                "session_id": session_id,
                "model": os.environ["OPENAI_VISION_MODEL"],
            },
            session_id=session_id,
        )
        current_visual_observations.append(
            CurrentVisualObservation(
                description=observation,
                sender_identity=sender,
                session_id=session_id,
                captured_at=captured_at_timestamp,
                source_event_id=source_event_id,
            )
        )
        del current_visual_observations[:-5]
        logger.info("Recorded visual observation from %s", sender)
        await _publish_visual_observation_ack(
            {
                "ok": True,
                "visual_request_id": visual_request_id,
                "request_sender_identity": sender,
                "description": observation,
                "artifact_uri": artifact_uri,
                "captured_at": captured_at,
            }
        )
        return {
            "ok": True,
            "description": observation,
            "captured_at": captured_at,
            "source_event_id": source_event_id,
            "scope": "one current camera frame, not continuous video or identity recognition",
        }

    async def _observe_camera() -> dict[str, Any]:
        try:
            response = await ctx.room.local_participant.perform_rpc(
                destination_identity=expected_participant_identity,
                method="marvain.camera_frame",
                payload=json.dumps({"session_id": session_id}),
            )
        except rtc.RpcError as exc:
            logger.warning("Camera frame request failed: %s", exc)
            return {"ok": False, "error": "camera_frame_request_failed", "detail": str(exc)}
        frame = json.loads(response)
        if frame.get("ok") is not True:
            return {"ok": False, "error": str(frame.get("error") or "camera_frame_unavailable")}
        return await _process_visual_observation_message(
            sender=expected_participant_identity,
            message_session_id=_require_runtime_text(frame.get("session_id"), "camera session_id"),
            artifact_uri=_require_runtime_text(frame.get("artifact_uri"), "camera artifact_uri"),
            captured_at=_require_runtime_text(frame.get("captured_at"), "camera captured_at"),
            visual_request_id=str(uuid4()),
        )

