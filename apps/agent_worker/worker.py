    def on_conversation_item_added(event: ConversationItemAddedEvent) -> None:
        """Forward transcript chunks to the Hub for persistence."""
        item = event.item
        # Only process ChatMessage items, skip type discriminators
        if not hasattr(item, "role") or not hasattr(item, "text_content"):
            return

        role = item.role
        text = item.text_content

        # Only ingest assistant messages here. User voice transcripts are handled
        # via UserInputTranscribedEvent so we can attach speaker_id.
        if role != "assistant" or not text:
            return

        logger.debug(f"Conversation item ({role}): {text[:50]}...")
        try:
            source_event_id = hub_ingest_transcript(
                space_id=space_id,
                text=text,
                role=role,
                participant_identity=None,
                input_modality="voice",
                session_id=session_id,
            )
        except Exception as exc:
            _create_background_task(
                _report_worker_error(
                    operation="transcript.ingest.assistant_voice",
                    code="transcript_ingest_failed",
                    error=exc,
                    retryable=True,
                ),
                operation="worker.error.transcript_ingest",
            )
            raise
        if AUTOSAVE_EPISODIC_MEMORIES:
            # Auto-save as episodic memory
            if source_event_id and source_event_id != "privacy_mode":
                for classification in classify_memory_for_capture(
                    text=text,
                    modality="audio",
                    source_event_id=source_event_id,
                    actor_type="agent",
                    source="livekit_assistant_voice",
                    space_id=space_id,
                    session_id=session_id,
                    room_name=ctx.room.name,
                    worker_version=worker_version,
                ):
                    _create_memory_with_error_event(
                        space_id=space_id,
                        content=text,
                        tier=classification.kind,
                        metadata={
                            "role": role,
                            "input_modality": "voice",
                            "room_name": ctx.room.name,
                            "room_session_id": room_session_id,
                            "memory_classification": classification.as_metadata(),
                        },
                        source_event_id=source_event_id,
                        session_id=session_id,
                    )

