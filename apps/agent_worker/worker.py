def hub_ingest_transcript(
    *,
    space_id: str,
    text: str,
    role: str,
    participant_identity: str | None = None,
    input_modality: str = "voice",
    session_id: str | None = None,
) -> str:
    """Send a transcript chunk to the Hub for persistence.

    Args:
        space_id: The Marvain space ID (from room name)
        text: The transcript text
        role: Either "user" or "assistant"
        participant_identity: The LiveKit participant identity
        input_modality: Either "voice" or "text"
    """
    event_id = hub_ingest_event(
        space_id=space_id,
        event_type="transcript_chunk",
        payload={
            "text": text,
            "role": role,
            "participant_identity": participant_identity,
            "source": "livekit_agent_worker",
            "input_modality": input_modality,
            "session_id": session_id,
            "occurred_at": _isoformat_utc(),
            "occurrence_time_basis": "transcript_produced_at",
        },
        session_id=session_id,
    )
    logger.debug("Ingested transcript (%s): %s...", role, text[:50])
    return event_id


@dataclass(frozen=True)
class PendingMemorySubmission:
    memory_id: str
    source_event_id: str
    semantic_sync_id: str
    status: str = "pending"


def hub_create_memory(
    *,
    space_id: str,
    content: str,
    tier: str = "episodic",
    metadata: dict | None = None,
    source_event_id: str,
    session_id: str | None = None,
) -> PendingMemorySubmission:
    """Queue a memory in the Hub's existing canonical writer workflow.

    Args:
        space_id: The Marvain space ID
        content: The memory content text
        tier: Memory tier (episodic, semantic, procedural)
        metadata: Additional metadata (input_modality, role, room_name, etc.)
    """
    body = _post_hub_json(
        path="/v1/memories",
        operation="memory.create",
        payload={
            "space_id": _require_runtime_text(space_id, "space_id"),
            "tier": tier,
            "content": content,
            "metadata": metadata or {},
            "source_event_id": _require_runtime_text(source_event_id, "source_event_id"),
            "session_id": session_id,
        },
    )
    if body.get("status") != "pending":
        raise WorkerContractError("memory submission response must report pending canonical persistence")
    submission = PendingMemorySubmission(
        memory_id=_require_runtime_text(body.get("memory_id"), "pending memory_id"),
        source_event_id=_require_runtime_text(body.get("source_event_id"), "pending source_event_id"),
        semantic_sync_id=_require_runtime_text(body.get("semantic_sync_id"), "pending semantic_sync_id"),
    )
    logger.info("Memory queued for canonical persistence: %s", submission.semantic_sync_id)
    return submission


