def _event_matches_session(ev: dict, current_session_id: str | None) -> bool:
    if not current_session_id:
        return False
    event_session_id = str(ev.get("session_id") or "").strip()
    return event_session_id == current_session_id


def _event_type_is_visual_observation(event_type: str) -> bool:
    normalized = str(event_type or "").strip().lower().replace("_", ".")
    if normalized in VISUAL_EVENT_TYPES:
        return True
    return any(
        normalized.startswith(prefix) and normalized.endswith(".observation") for prefix in VISUAL_EVENT_TYPE_PREFIXES
    )


def _format_visual_observation_value(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, (int, float, bool)):
        return str(value)
    if isinstance(value, list):
        return ", ".join(str(item).strip() for item in value if str(item).strip())
    if isinstance(value, dict):
        parts = []
        for key, item in value.items():
            text = _format_visual_observation_value(item)
            if text:
                parts.append(f"{key}: {text}")
        return "; ".join(parts)
    return str(value).strip()


def _extract_visual_observation_text(ev: dict) -> str:
    payload = ev.get("payload") if isinstance(ev.get("payload"), dict) else {}
    for field in VISUAL_OBSERVATION_FIELDS:
        text = _format_visual_observation_value(payload.get(field))
        if text:
            return text
    return ""


def _extract_openai_response_text(resp: dict) -> str:
    texts: list[str] = []
    for item in resp.get("output") or []:
        if not isinstance(item, dict):
            continue
        for content in item.get("content") or []:
            if not isinstance(content, dict):
                continue
            text = content.get("text")
            if text:
                texts.append(str(text).strip())
    return "\n".join(t for t in texts if t).strip()


def _describe_visual_artifact(artifact_uri: str, *, agent_id: str) -> str | None:
    """Describe a current-session visual artifact with OpenAI vision.

    Returning ``None`` keeps the truthfulness guard closed: artifact references
    alone are not visual observations.
    """
    artifact_uri = str(artifact_uri or "").strip()
    api_key = str(os.getenv("OPENAI_API_KEY") or "").strip()
    if not artifact_uri or not api_key or not artifact_uri.startswith("s3://"):
        return None

    try:
        import base64
        import urllib.parse

        import boto3

        parsed = urllib.parse.urlparse(artifact_uri)
        bucket = parsed.netloc
        key = parsed.path.lstrip("/")
        expected_bucket = _require_runtime_text(os.getenv("ARTIFACT_BUCKET"), "ARTIFACT_BUCKET")
        if bucket != expected_bucket or not key.startswith(f"visual/agent_id={agent_id}/"):
            raise WorkerContractError("visual artifact must belong to the current agent's configured bucket prefix")

        s3 = boto3.client("s3")
        obj = s3.get_object(Bucket=bucket, Key=key)
        image_bytes = obj["Body"].read(4_000_001)
        if len(image_bytes) > 4_000_000:
            logger.warning("Skipping visual description: artifact exceeds size limit")
            return None

        content_type = str(obj.get("ContentType") or "image/jpeg")
        image_data_url = f"data:{content_type};base64,{base64.b64encode(image_bytes).decode('ascii')}"
        response = requests.post(
            "https://api.openai.com/v1/responses",
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
            json={
                "model": _require_runtime_text(os.getenv("OPENAI_VISION_MODEL"), "OPENAI_VISION_MODEL"),
                "input": [
                    {
                        "role": "system",
                        "content": [
                            {
                                "type": "input_text",
                                "text": (
                                    "You produce concise, objective visual observations for a live assistant. "
                                    "Describe only visible facts in the image. Do not infer identities, private "
                                    "attributes, or unavailable context."
                                ),
                            }
                        ],
                    },
                    {
                        "role": "user",
                        "content": [
                            {
                                "type": "input_text",
                                "text": "Describe the current camera frame in one or two short sentences.",
                            },
                            {"type": "input_image", "image_url": image_data_url},
                        ],
                    },
                ],
                "max_output_tokens": 160,
            },
            timeout=20,
        )
        if not response.ok:
            logger.warning(
                "Visual description request failed: status=%s body=%s", response.status_code, response.text[:200]
            )
            return None
        text = _extract_openai_response_text(response.json())
        return text[:800] if text else None
    except Exception as exc:
        logger.warning("Failed to describe visual artifact: %s", exc.__class__.__name__)
        return None


def _build_current_visual_observation_block(
    events: list[dict], *, current_session_id: str | None, now: datetime | None = None
) -> str:
    """Build same-session textual visual observations for the model prompt.

    Artifact-only events are intentionally ignored here. A screenshot/image/video
    reference is not visual access until another component has produced textual
    observation context for this exact session.
    """
    observations = []
    for ev in events or []:
        if not _event_matches_session(ev, current_session_id):
            continue
        normalized_type = str(ev.get("type") or "").strip().lower().replace("_", ".")
        if normalized_type == "visual.observation.invalidated":
            break
        if not _event_type_is_visual_observation(str(ev.get("type") or "")):
            continue
        payload = ev.get("payload") if isinstance(ev.get("payload"), dict) else {}
        try:
            validate_livekit_message_freshness(
                payload.get("captured_at"),
                field_name="captured_at",
                max_age_seconds=VISUAL_OBSERVATION_MAX_AGE_SECONDS,
                now=now,
            )
        except LiveKitMessageValidationError:
            continue
        text = _extract_visual_observation_text(ev)
        if not text:
            continue
        event_id = str(ev.get("event_id") or "").strip()
        if not event_id:
            continue
        observations.append(f"{text[:500]} (source event {event_id}, captured {payload['captured_at']})")
        if len(observations) >= 5:
            break
    if not observations:
        return ""
    lines = ["## Current Session Visual Observations"]
    lines.extend(f"- {text}" for text in observations)
    return "\n".join(lines)


def _build_context_block(events: list[dict], memories: list[dict], *, current_session_id: str | None = None) -> str:
    """Build context block for agent instructions.

    Summarizes recent conversation and relevant memories.
    """
    parts = []

    visual_context = _build_current_visual_observation_block(events, current_session_id=current_session_id)
    if visual_context:
        parts.append(visual_context)

    # Add memory context if available
    if memories:
        parts.append("## Relevant Memories")
        for mem in memories:
            tier = mem.get("tier", "")
            content = mem.get("content", "")[:500]  # Truncate long content
            source_note = _format_memory_source_note(mem)
            role = mem.get("role", "unknown")
            parts.append(f"- [{tier}; speaker={role}; at={mem.get('effective_at')}] {content}{source_note}")

    # Add recent conversation summary if available
    if events:
        parts.append("\n## Recent Conversation in This Space")
        # Group by role and summarize - show last 10 events max
        session_events = [ev for ev in events if _event_matches_session(ev, current_session_id)]
        for ev in reversed(session_events[:10]):
            payload = ev.get("payload", {})
            role = payload.get("role", "unknown")
            text = payload.get("text", "")[:200]  # Truncate
            if text and ev.get("type") == "transcript_chunk":
                speaker = "User" if role == "user" else "You"
                parts.append(f"- {speaker}: {text}")

    if not parts:
        return ""

    return "\n".join(parts)


